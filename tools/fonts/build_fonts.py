#!/usr/bin/env python3
"""Regenerate fonts_data.h from TrueType files.

Every document font is embedded in the wasm module as a raw TTF array, subset to
the charset the document model can hold (WinAnsi + Latin-1 + typographic
quotes/dashes). The editor loads faces from memory at startup, so nothing is
fetched at runtime.

    python3 tools/fonts/build_fonts.py --srcdir <dir-with-ttfs> --out fonts_data.h

Adding a family = add it to FAMILIES (id, display name, Word alias, class) and
rerun; main.cpp reads kFontFaces / kDocFamilyName and needs no change beyond the
family count it already derives from `kDocFamilyCount`.
"""
import argparse
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

# Everything Word can put in a WinAnsi-encoded paragraph, plus the characters the
# editor's own UI uses (arrows, math signs, bullets, quotes, dashes).
UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) +
    [0x0131, 0x0152, 0x0153, 0x0160, 0x0161, 0x0178, 0x017D, 0x017E, 0x0192,
     0x02C6, 0x02DC, 0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D,
     0x201E, 0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203A, 0x2044,
     0x20AC, 0x2113, 0x2122, 0x2126, 0x2202, 0x2206, 0x220F, 0x2211, 0x2212,
     0x221A, 0x2248, 0x2260, 0x2264, 0x2265, 0x25CA, 0xFB01, 0xFB02]
)

# id -> (display name, Word alias written to .docx, PDF class 0=sans 1=serif 2=mono, file prefix)
FAMILIES = [
    ("DejaVu Sans",       "",                 0, "DejaVuSans"),
    ("DejaVu Serif",      "",                 1, "DejaVuSerif"),
    ("DejaVu Sans Mono",  "",                 2, "DejaVuSansMono"),
    ("Liberation Sans",   "Arial",            0, "LiberationSans"),
    ("Liberation Serif",  "Times New Roman",  1, "LiberationSerif"),
    ("Liberation Mono",   "Courier New",      2, "LiberationMono"),
    ("Carlito",           "Calibri",          0, "Carlito"),
    ("Caladea",           "Cambria",          1, "Caladea"),
]

# candidate file names per face; DejaVu ships no "-Regular" and calls italics "Oblique"
FACE_FILES = [
    (["{p}.ttf", "{p}-Regular.ttf"], "regular"),
    (["{p}-Bold.ttf"], "bold"),
    (["{p}-Italic.ttf", "{p}-Oblique.ttf"], "italic"),
    (["{p}-BoldItalic.ttf", "{p}-BoldOblique.ttf"], "boldItalic"),
]


def subset_face(path):
    opts = subset.Options()
    opts.layout_features = []          # stb_truetype applies no GSUB/GPOS
    opts.name_IDs = ["*"]
    opts.name_legacy = True
    opts.notdef_outline = True
    opts.recalc_bounds = True
    # stb_truetype rasterises without TT hinting, so the hinting programs are
    # dead weight: dropping them roughly halves each face.
    opts.hinting = False
    opts.desubroutinize = True
    opts.drop_tables += ["DSIG", "gasp", "hdmx", "VDMX", "LTSH", "kern", "PCLT", "FFTM",
                      "GPOS", "GSUB", "GDEF", "BASE", "JSTF", "MATH"]
    font = TTFont(path, lazy=False)
    subs = subset.Subsetter(options=opts)
    subs.populate(unicodes=UNICODES)
    subs.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def array(name, data):
    out = [f"static const unsigned int {name}Len = {len(data)};",
           f"static const unsigned char {name}[{len(data)}] = {{"]
    line = []
    for i, b in enumerate(data):
        line.append(f"{b:3d}")
        if len(line) == 20:
            out.append(",".join(line) + ",")
            line = []
    if line:
        out.append(",".join(line))
    out.append("};")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--srcdir", required=True)
    ap.add_argument("--out", default="fonts_data.h")
    args = ap.parse_args()

    parts = [
        "// Generated by tools/fonts/build_fonts.py -- do not edit by hand.",
        "//",
        "// Document faces, subset to WinAnsi + Latin-1 + typographic punctuation.",
        "// Families 3.. are free metric-compatible replacements for the Word",
        "// defaults (Arial/Times New Roman/Courier New/Calibri/Cambria); the .docx",
        "// writer emits the Word name so exchanged files open with the right layout.",
        "#pragma once",
        "",
        f"static const int kDocFamilyCount = {len(FAMILIES)};",
        "",
    ]

    entries = []
    for fam_id, (display, alias, cls, prefix) in enumerate(FAMILIES):
        faces = []
        for cands, field in FACE_FILES:
            path = next((os.path.join(args.srcdir, c.format(p=prefix)) for c in cands
                         if os.path.exists(os.path.join(args.srcdir, c.format(p=prefix)))), None)
            if not path:
                sys.exit(f"missing {prefix} {field} in {args.srcdir}")
            data = subset_face(path)
            name = f"kFont{fam_id}_{field}"
            parts.append(array(name, data))
            parts.append("")
            faces.append((name, len(data)))
            print(f"{os.path.basename(path)}: {len(data)/1024:.1f} KB")
        entries.append((fam_id, faces))

    parts.append("struct EmbeddedFace { const unsigned char* data; unsigned int len; };")
    parts.append("// [family][regular, bold, italic, bold-italic]")
    parts.append("static const EmbeddedFace kFontFaces[kDocFamilyCount][4] = {")
    for fam_id, faces in entries:
        row = ", ".join(f"{{ {n}, {n}Len }}" for n, _ in faces)
        parts.append(f"    {{ {row} }},   // {FAMILIES[fam_id][0]}")
    parts.append("};")
    parts.append("")
    parts.append("static const char* kDocFamilyName[kDocFamilyCount] = {")
    for display, alias, cls, prefix in FAMILIES:
        parts.append(f'    "{display}",')
    parts.append("};")
    parts.append("")
    parts.append("// Word name written into .docx runs (empty = write the display name)")
    parts.append("static const char* kDocFamilyAlias[kDocFamilyCount] = {")
    for display, alias, cls, prefix in FAMILIES:
        parts.append(f'    "{alias}",')
    parts.append("};")
    parts.append("")
    parts.append("// PDF base-14 class: 0 sans, 1 serif, 2 mono")
    parts.append("static const int kDocFamilyClass[kDocFamilyCount] = {")
    for display, alias, cls, prefix in FAMILIES:
        parts.append(f"    {cls},")
    parts.append("};")
    parts.append("")
    parts.append("static const char* kDocFamilyShort[kDocFamilyCount] = {")
    short = ["Sans", "Serif", "Mono", "Arial", "Times", "Courier",
             "Calibri", "Cambria", "Georgia", "Garamond"]
    for i, (display, alias, cls, prefix) in enumerate(FAMILIES):
        parts.append(f'    "{short[i]}",')
    parts.append("};")
    parts.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(parts))
    print("wrote", args.out, f"{os.path.getsize(args.out)/1024/1024:.2f} MB")


if __name__ == "__main__":
    main()
