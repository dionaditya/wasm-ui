#!/usr/bin/env python3
"""Generate pdf_glyphs.h — substitute TTFs for the native PDF renderer.

Most PDFs produced by LaTeX (and plenty of others) reference Type 1 faces
without embedding them (NimbusRomNo9L, CMR, CMSY, CMMI, CMTT...). A rasterizer
cannot draw outlines it does not have, so the renderer substitutes the closest
embedded face while still using the PDF's own /Widths for advances — the
lines break in exactly the right places, only the glyph shapes come from here.

The .docx editor's font set (fonts_data.h) is subset to WinAnsi + Latin-1 and
has no Greek or math operators, which a paper's equations need, so this header
carries its own wider subsets:

    python3 tools/fonts/build_pdf_glyphs.py --srcdir <ttf-dir> --out pdf_glyphs.h
"""
import argparse
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +
    list(range(0x2B0, 0x2E0)) +          # spacing modifiers (breve, caron, ring...)
    [0x131, 0x237, 0x141, 0x142, 0x152, 0x153, 0x160, 0x161, 0x17D, 0x17E, 0x192] +
    list(range(0x370, 0x400)) +          # greek
    list(range(0x2000, 0x2070)) +        # general punctuation
    list(range(0x20A0, 0x20B0)) +
    list(range(0x2100, 0x2150)) +
    list(range(0x2190, 0x2200)) +        # arrows
    list(range(0x2200, 0x2300)) +        # math operators
    list(range(0x2300, 0x2400)) +
    list(range(0x25A0, 0x2600)) +        # geometric shapes
    [0xFB00, 0xFB01, 0xFB02, 0xFB03, 0xFB04]
)

# face key -> (family file prefix, style file suffix)
FACES = [
    ("serif_regular",   "DejaVuSerif",     ""),
    ("serif_bold",      "DejaVuSerif",     "-Bold"),
    ("serif_italic",    "DejaVuSerif",     "-Italic"),
    ("sans_regular",    "DejaVuSans",      ""),
    ("mono_regular",    "DejaVuSansMono",  ""),
]


def subset_face(path):
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]
    opts.name_legacy = True
    opts.notdef_outline = True
    opts.drop_tables += ["DSIG"]
    opts.recalc_bounds = True
    font = TTFont(path, recalcTimestamp=False)
    ss = subset.Subsetter(options=opts)
    ss.populate(unicodes=UNICODES)
    ss.subset(font)
    out = io_bytes()
    font.save(out)
    return out.getvalue()


class io_bytes:
    def __init__(self):
        self.buf = bytearray()

    def write(self, b):
        self.buf += b

    def getvalue(self):
        return bytes(self.buf)


def emit_array(name, data):
    lines = [f"static const unsigned int {name}Len = {len(data)};",
             f"static const unsigned char {name}[{len(data)}] = {{"]
    row = []
    for i, b in enumerate(data):
        row.append(str(b))
        if len(row) == 24:
            lines.append("  " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ",".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--srcdir", required=True, help="directory holding DejaVuSerif.ttf etc")
    ap.add_argument("--out", default="pdf_glyphs.h")
    args = ap.parse_args()

    parts = ["// Generated by tools/fonts/build_pdf_glyphs.py -- do not edit by hand.",
             "//",
             "// Substitute outlines for non-embedded PDF fonts: Latin-1, Latin Ext-A,",
             "// Greek, punctuation, arrows, math operators and ligatures. The PDF's own",
             "// /Widths still drive advances; only the glyph shapes come from here.",
             "#pragma once", ""]
    entries = []
    for key, family, style in FACES:
        path = os.path.join(args.srcdir, family + style + ".ttf")
        if not os.path.exists(path):
            sys.exit(f"missing {path}")
        data = subset_face(path)
        name = "kPdfFace_" + key
        parts.append(f"// {family}{style}  {len(data)} bytes")
        parts.append(emit_array(name, data))
        parts.append("")
        entries.append((key, name))

    parts.append("struct PdfSubFont { const char* key; const unsigned char* data; unsigned int len; };")
    parts.append("static const PdfSubFont kPdfSubFonts[] = {")
    for key, name in entries:
        parts.append(f'  {{"{key}", {name}, {name}Len}},')
    parts.append("};")
    parts.append("static const int kPdfSubFontCount = %d;" % len(entries))
    with open(args.out, "w") as f:
        f.write("\n".join(parts) + "\n")
    total = sum(os.path.getsize(os.path.join(args.srcdir, fam + st + ".ttf")) for _, fam, st in FACES)
    print(f"wrote {args.out}: {os.path.getsize(args.out)} bytes (source faces {total} bytes)")


if __name__ == "__main__":
    main()
